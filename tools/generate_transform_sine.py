"""Generate the Q10, 256-entry, one-turn P1GL sine table."""
from math import sin, tau
from pathlib import Path

table = Path(__file__).resolve().parents[1] / 'generated/transform-sine.ac'
values = [round(1024 * sin(tau * angle / 256)) for angle in range(256)]
lines = ['// Generated by tools/generate_transform_sine.py.', 'gtf_sine,']
for start in range(0, len(values), 8):
    row = (f'{"-" if n < 0 else ""}0d{abs(n)}' for n in values[start:start + 8])
    lines.append('        ' + '; '.join(row))
table.write_text('\n'.join(lines) + '\n')
