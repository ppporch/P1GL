"""Convert the bundled Hershey JHF face into banked PDP-1 stroke data.
Original format, source and distribution terms remain in fonts/.
"""
import hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def load_font():
    rows=(ROOT/'fonts/futural.jhf').read_text().splitlines()
    assert len(rows)>=95
    glyphs=[]
    for ascii_code,line in enumerate(rows[:95],32):
        count=int(line[5:8]);data=line[8:]
        assert len(data)==count*2
        left,right=ord(data[0])-82,ord(data[1])-82
        strokes=[];stroke=[]
        for i in range(2,len(data),2):
            pair=data[i:i+2]
            if pair==' R':
                if stroke:strokes.append(stroke);stroke=[]
            else:stroke.append((ord(pair[0])-82-left,9-(ord(pair[1])-82)))
        if stroke:strokes.append(stroke)
        pts=[p for s in strokes for p in s]
        bounds=[min(x for x,y in pts),max(x for x,y in pts),min(y for x,y in pts),max(y for x,y in pts)] if pts else [0,0,0,0]
        assert all(0<=x<64 and -16<=y<48 for x,y in pts)
        glyphs.append(dict(ascii=ascii_code,advance=right-left,bounds=bounds,strokes=strokes))
    return glyphs

def generate():
    glyphs=load_font()
    out=['// Generated by tools/generate_vfont.py; see fonts/HERSHEY-NOTICE.txt.',
         '// One vertex word: X[5:0], (Y+16)[11:6], pen-up bit 12; END bit 17.',
         'bank P1GL_FONT_BANK','0100/','gv_font_index,']
    for g in glyphs:
        vals=[f'gv_glyph_{g["ascii"]}:P1GL_FONT_BANK',f'0d{g["advance"]}']
        vals += [('-' if v<0 else '')+f'0d{abs(v)}' for v in g['bounds']]
        out.append('        '+'; '.join(vals))
    words=570
    for g in glyphs:
        out.append(f'gv_glyph_{g["ascii"]},')
        for stroke in g['strokes']:
            for i,(x,y) in enumerate(stroke):
                out.append(f'        {x|((y+16)<<6)|(4096 if i==0 else 0):06o}')
                words+=1
        out.append('        0400000');words+=1
    out += ['assert . <= 07777, "vector font exceeds its bank"','bank 0']
    data='\n'.join(out)+'\n'
    (ROOT/'generated/vector-font.ac').write_text(data)
    report=dict(source='https://github.com/kamalmostafa/hershey-fonts',upstream_commit='1356bf2f83d380fcef68c887e88675eb9d445d86',face='futural.jhf',glyphs=len(glyphs),font_words=words,source_sha256=hashlib.sha256((ROOT/'fonts/futural.jhf').read_bytes()).hexdigest())
    (ROOT/'generated/vector-font.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))
if __name__=='__main__':generate()
